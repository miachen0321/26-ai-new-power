function predictIris(sepalLength, sepalWidth, petalLength, petalWidth) {
  const x = [sepalLength, sepalWidth, petalLength, petalWidth];
  const z = x.map((v, i) => (v - IRISscaler.mean[i]) / IRISscaler.scale[i]);
  let h = z;
  for (let L of IRISlayers) {
    const out = [];
    for (let j = 0; j < L.b.length; j++) {
      let s = L.b[j];
      for (let i = 0; i < h.length; i++) s += h[i] * L.W[i][j];
      out.push(s);
    }
    if (L === IRISlayers[IRISlayers.length - 1]) {
      let max = Math.max(...out);
      let exps = out.map((v) => Math.exp(v - max));
      let sum = exps.reduce((a, b) => a + b, 0);
      h = exps.map((e) => e / sum);
    } else {
      h = out.map((v) => Math.max(v, 0));
    }
  }
  return h;
}

function predictAI4I(airTemperature, processTemperature, rotationalSpeed, torque, toolWear, type) {
  const torqueSpeedProduct = torque * rotationalSpeed;
  const temperatureDifference = processTemperature - airTemperature;
  const nums = [
    airTemperature, processTemperature, rotationalSpeed, torque,
    toolWear, torqueSpeedProduct, temperatureDifference
  ];
  const z = nums.map((v, i) => (v - AI4Imean[i]) / AI4Iscale[i]);
  z.push(type === "M" ? 1 : 0, type === "H" ? 1 : 0);
  let s = AI4Iintercept;
  for (let i = 0; i < z.length; i++) s += z[i] * AI4Icoef[i];
  const probability = 1 / (1 + Math.exp(-s));
  return { failure: probability, ok: 1 - probability };
}

