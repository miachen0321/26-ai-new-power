if (typeof document !== "undefined") {
  const resultBox = document.getElementById("result");
  const predBox = document.getElementById("result-pred");
  const tableBox = document.getElementById("result-table");
  const noteBox = document.getElementById("result-note");

  function show(title, rows, note) {
    predBox.textContent = title;
    let html = "<table>";
    for (const [label, prob] of rows) {
      html += "<tr><td>" + label + "</td><td>" + (prob * 100).toFixed(2) + "%</td>" +
        "<td><div class='bar'><span style='width:" + (prob * 100).toFixed(1) + "%'></span></div></td></tr>";
    }
    html += "</table>";
    tableBox.innerHTML = html;
    noteBox.textContent = note || "";
    resultBox.style.display = "block";
  }

  function percentFromProb(p) {
    return { "未失效 OK": 1 - p, "失效 FAILURE": p };
  }

  function readInputs(ids) {
    return ids.map((id) => parseFloat(document.getElementById(id).value));
  }

  function requireInputs(vals) {
    for (const v of vals) {
      if (Number.isNaN(v)) {
        noteBox.textContent = "尚有欄位未填數值";
        resultBox.style.display = "block";
        return false;
      }
    }
    return true;
  }

  function runIris() {
    const vals = readInputs(["i-sepal-length", "i-sepal-width", "i-petal-length", "i-petal-width"]);
    if (!requireInputs(vals)) return;
    const probs = predictIris(...vals);
    let best = 0;
    probs.forEach((p, i) => { if (p > probs[best]) best = i; });
    show(
      "預測類別：" + IRISclasses[best],
      probs.map((p, i) => [IRISclasses[i], p]).sort((a, b) => b[1] - a[1]),
      "期望三個機率總和 = 100%"
    );
  }

  function runAI4I() {
    const vals = readInputs(["a-air", "a-process", "a-rpm", "a-torque", "a-wear"]);
    if (!requireInputs(vals)) return;
    const type = document.getElementById("a-type").value;
    const prob = predictAI4I(...vals, type);
    const pairs = Object.entries(percentFromProb(prob.failure)).sort((a, b) => b[1] - a[1]);
    const failureProb = prob.failure;
    show(
      "故障機率：" + (failureProb * 100).toFixed(2) + "%（門檻 50%：" +
        (failureProb >= 0.5 ? "預測為故障" : "預測為正常") + "）",
      pairs,
      "派生特徵已自動補計（扭矩×轉速、溫度差），type 以 L 為對照組"
    );
  }

  document.getElementById("i-run").addEventListener("click", runIris);
  document.getElementById("a-run").addEventListener("click", runAI4I);
}

